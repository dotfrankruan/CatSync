#!/usr/bin/env python3
"""Render the CatSync benchmark SVGs from machine-readable results.

No network or third-party package is used. The input file is never modified.
The resulting SVGs include titles, labelled axes, units, sample counts and
explicit failure markers; they are readable in GitHub's light and dark themes.
"""
import argparse
import json
import math
import statistics
import xml.etree.ElementTree as ET
from pathlib import Path

W, H = 860, 480
PAD_L, PAD_R, PAD_T, PAD_B = 78, 30, 70, 126
BAR_COLORS = ["#4c78a8", "#f58518", "#54a24b", "#b279a2", "#e45756", "#72b7b2"]
DARK_CSS = """
<style>
text { fill: #1f2328; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; }
.axis { stroke: #57606a; stroke-width: 1.2; }
.grid { stroke: #d0d7de; stroke-width: 0.8; stroke-dasharray: 3 3; }
.legend-box { fill: none; stroke: #d0d7de; }
@media (prefers-color-scheme: dark) {
  text { fill: #e6edf3; }
  .axis { stroke: #8b949e; }
  .grid { stroke: #30363d; }
  .legend-box { stroke: #30363d; }
}
</style>
"""


def esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def svg_start(title, subtitle):
    root = ET.Element("svg", xmlns="http://www.w3.org/2000/svg", viewBox=f"0 0 {W} {H}", width=str(W), height=str(H), role="img", **{"aria-label": title})
    m = ET.SubElement(root, "metadata")
    m.text = "Generated by scripts/benchmarks/render.py from docs/assets/benchmarks/results.json"
    t = ET.SubElement(root, "title"); t.text = title
    st = ET.SubElement(root, "style"); st.text = DARK_CSS.split("<style>")[1].split("</style>")[0]
    t1 = ET.SubElement(root, "text", x="24", y="32", **{"font-size": "20", "font-weight": "700"}); t1.text = title
    t2 = ET.SubElement(root, "text", x="24", y="54", **{"font-size": "12", "fill": "#57606a"}); t2.text = subtitle
    return root


def add_text(root, x, y, text, size=12, anchor="start", weight=None, fill=None, rotate=False):
    attrs = {"x": str(x), "y": str(y), "font-size": str(size), "text-anchor": anchor}
    if weight:
        attrs["font-weight"] = weight
    if fill:
        attrs["fill"] = fill
    if rotate:
        attrs["transform"] = f"rotate(-90 {x} {y})"
    e = ET.SubElement(root, "text", **attrs); e.text = text
    return e


def add_line(root, x1, y1, x2, y2, cls="grid"):
    ET.SubElement(root, "line", x1=str(x1), y1=str(y1), x2=str(x2), y2=str(y2), **{"class": cls})


SHORT = {
    "daemon SSH-forward": "SSH-forward",
    "daemon direct QUIC": "direct QUIC",
    "daemon direct TCP": "direct TCP",
    "direct TCP streams=1": "TCP s=1",
    "direct TCP streams=4": "TCP s=4",
    "direct TCP streams=8": "TCP s=8",
    "legacy SSH": "legacy SSH",
    "pre-detach direct TCP (v0.2.0)": "old direct TCP",
}


def short_mode(mode):
    return SHORT.get(mode, mode)


def bar_chart(path, title, subtitle, rows, mode_order, value_fn, y_label, failure_note):
    valid = [r for r in rows if r.get("success") and r.get("_value") is not None]
    all_by_mode = {m: [r for r in rows if r.get("_mode") == m] for m in mode_order}
    vals = [r["_value"] for r in valid]
    ymax = max(vals + [1])
    # Pick a friendly axis: 0, step, 2*step, ... up to ceil(max/step)*step.
    raw = ymax / 5
    exp = 10 ** math.floor(math.log10(raw))
    for mult in (1, 2, 2.5, 5, 10):
        step = exp * mult
        if raw <= step:
            break
    ymax = math.ceil(ymax / step) * step or step
    ticks = max(1, round(ymax / step))
    plot_w = W - PAD_L - PAD_R
    plot_h = H - PAD_T - PAD_B
    root = svg_start(title, subtitle)
    # Axes and y grid.
    for i in range(ticks + 1):
        y = PAD_T + plot_h - plot_h * i / ticks
        add_line(root, PAD_L, y, PAD_L + plot_w, y)
        tick = step * i
        label = (f"{tick:g}" if tick < 10 else f"{tick:.0f}")
        add_text(root, PAD_L - 10, y + 4, label, 11, "end")
    add_line(root, PAD_L, PAD_T, PAD_L, PAD_T + plot_h, "axis")
    add_line(root, PAD_L, PAD_T + plot_h, PAD_L + plot_w, PAD_T + plot_h, "axis")
    add_text(root, 18, PAD_T + plot_h / 2, y_label, 12, "middle", None, None, rotate=True)
    # Bars, one group per mode.
    n = max(1, len(mode_order))
    group_w = plot_w / n
    bw = min(66, group_w * 0.55)
    for i, mode in enumerate(mode_order):
        rs = [r for r in all_by_mode[mode] if r.get("success") and r.get("_value") is not None]
        fails = [r for r in all_by_mode[mode] if not r.get("success")]
        cx = PAD_L + group_w * (i + 0.5)
        if rs:
            v = statistics.median(r["_value"] for r in rs)
            bh = plot_h * (v / ymax) if ymax else 0
            x = cx - bw / 2
            color = BAR_COLORS[i % len(BAR_COLORS)]
            ET.SubElement(root, "rect", x=f"{x:.1f}", y=f"{PAD_T + plot_h - bh:.1f}", width=f"{bw:.1f}", height=f"{bh:.1f}",
                          fill=color, stroke="#30363d", **{"stroke-width": "1"})
            add_text(root, cx, PAD_T + plot_h - bh - 8, f"{v:.1f}", 11, "middle", "600")
            add_text(root, cx, PAD_T + plot_h + 20, f"OK {len(rs)}/{len(all_by_mode[mode])}", 10, "middle")
        else:
            add_text(root, cx, PAD_T + plot_h - 20, "NO\nSUCCESS", 11, "middle", "600")
        if fails:
            # Failure count is explicit; the hatch only reinforces the label.
            ET.SubElement(root, "rect", x=f"{cx - bw/2:.1f}", y=f"{PAD_T + plot_h - 12:.1f}", width=f"{bw:.1f}", height="12",
                          fill="url(#failhatch)", stroke="#e45756")
            add_text(root, cx, PAD_T + plot_h + 36, f"FAIL {len(fails)}", 10, "middle", "600", "#e45756")
        add_text(root, cx, PAD_T + plot_h + 54, short_mode(mode), 10, "middle")
    defs = ET.SubElement(root, "defs")
    pat = ET.SubElement(defs, "pattern", id="failhatch", width="6", height="6", patternUnits="userSpaceOnUse", patternTransform="rotate(45)")
    ET.SubElement(pat, "rect", width="6", height="6", fill="#f6d6d6")
    ET.SubElement(pat, "line", x1="0", y1="0", x2="0", y2="6", stroke="#e45756", **{"stroke-width": "2"})
    add_text(root, PAD_L, H - 22, failure_note, 10)
    add_text(root, W - PAD_R, H - 22, "bar = median of successful runs", 10, "end")
    ET.indent(root, space="  ")
    path.write_text(ET.tostring(root, encoding="unicode") + "\n")


def load_results(path):
    doc = json.loads(Path(path).read_text())
    for r in doc.get("runs", []):
        r["_mode"] = r.get("mode", "?")
        if r.get("success") and r.get("elapsed_ms"):
            r["_value"] = r["bytes"] * 8 / (r["elapsed_ms"] / 1000) / 1e6
    return doc


def mode_order(doc):
    order = []
    for r in doc["runs"]:
        m = r.get("mode")
        if m not in order:
            order.append(m)
    return order


def render_throughput(doc, outdir, direction, dataset_id, title, filename):
    rows = [r for r in doc["runs"] if r.get("direction") == direction and r.get("dataset") == dataset_id and r.get("mode") != "legacy baseline"]
    order = []
    for r in rows:
        if r["mode"] not in order:
            order.append(r["mode"])
    order.sort(key=lambda m: (m.startswith("pre-detach"), m))
    bar_chart(outdir / filename, title,
              f"Unrestricted public network · dataset {dataset_id} · median effective throughput",
              rows, order, None, "Effective throughput (Mbps)",
              "Failures are never dropped; FAIL counts include timeout and protocol errors.")


def render_handoff(doc, outdir):
    rows = [r for r in doc["runs"] if r.get("dataset") == "large-128MiB" and r.get("direction") == "upload"
            and r.get("success") and r.get("timing_ms")]
    modes = [m for m in ("daemon direct TCP", "daemon direct QUIC") if any(r["mode"] == m for r in rows)]
    if not modes:
        modes = sorted({r["mode"] for r in rows})
    phases = [("bootstrap/auth", "data_control_ready"), ("handoff", "ssh_closed"), ("transfer+verify", "client_close")]
    root = svg_start("Direct upload: bootstrap, handoff, transfer",
                     "Median wall-clock phases from successful detached runs (large-128MiB; unrestricted network; log scale)")
    plot_w = W - PAD_L - PAD_R
    plot_h = H - PAD_T - PAD_B
    data = {}
    for m in modes:
        rs = [r for r in rows if r["mode"] == m]
        t = {"base": [], "ready": [], "handoff": [], "close": []}
        for r in rs:
            ev = r["timing_ms"]
            t["base"].append(ev.get("bootstrap_start", 0))
            t["ready"].append(ev.get("data_control_ready", ev.get("bootstrap_start", 0)))
            t["handoff"].append(ev.get("ssh_closed", ev.get("handoff_ack", ev.get("data_control_ready", 0))))
            t["close"].append(ev.get("client_close", ev.get("ssh_closed", 0)))
        med = {k: statistics.median(v) for k, v in t.items()}
        data[m] = {"bootstrap/auth": max(0.1, med["ready"] - med["base"]),
                   "handoff": max(0.1, med["handoff"] - med["ready"]),
                   "transfer+verify": max(0.1, med["close"] - med["handoff"])}
    max_val = max(max(v.values()) for v in data.values()) if data else 1
    log_max = max(1, math.ceil(math.log10(max_val)))
    for i in range(1, log_max + 1):
        y = PAD_T + plot_h - plot_h * i / log_max
        add_line(root, PAD_L, y, PAD_L + plot_w, y)
        val = 10 ** i
        lbl = f"{val/1000:g}k" if val >= 1000 else f"{val:g}"
        add_text(root, PAD_L - 10, y + 4, lbl, 11, "end")
    add_line(root, PAD_L, PAD_T, PAD_L, PAD_T + plot_h, "axis")
    add_line(root, PAD_L, PAD_T + plot_h, PAD_L + plot_w, PAD_T + plot_h, "axis")
    add_text(root, 20, PAD_T + plot_h / 2, "Elapsed (ms; log scale)", 12, "middle", None, None, rotate=True)
    n = max(1, len(modes))
    group_w = plot_w / n
    nb = len(phases)
    bw = min(54, group_w * 0.7 / nb)
    for i, m in enumerate(modes):
        cx = PAD_L + group_w * (i + 0.5)
        group_start = cx - (nb * bw) / 2
        for j, (label, _) in enumerate(phases):
            v = data[m][label]
            bh = plot_h * (math.log10(v) / log_max)
            x = group_start + j * bw
            color = ["#4c78a8", "#f58518", "#54a24b"][j]
            ET.SubElement(root, "rect", x=f"{x:.1f}", y=f"{PAD_T + plot_h - bh:.1f}", width=f"{max(1,bw-2):.1f}", height=f"{max(1,bh):.1f}",
                          fill=color, stroke="#30363d", **{"stroke-width": "0.8"})
            if bh > 16:
                add_text(root, x + bw / 2, PAD_T + plot_h - bh + 14, f"{v:.0f}", 10, "middle")
        add_text(root, cx, PAD_T + plot_h + 22, m, 10, "middle")
        add_text(root, cx, PAD_T + plot_h + 40, f"n={len([r for r in rows if r['mode']==m])}", 10, "middle")
    lx = PAD_L
    for j, (label, _) in enumerate(phases):
        ET.SubElement(root, "rect", x=str(lx), y=str(H - 42), width="14", height="10", fill=["#4c78a8", "#f58518", "#54a24b"][j])
        add_text(root, lx + 20, H - 33, label, 11)
        lx += 190
    add_text(root, PAD_L, H - 18, "Bars below 1 ms are clamped to 1 ms so they remain visible on the log axis.", 10)
    ET.indent(root, space="  ")
    (outdir / "handoff-latency.svg").write_text(ET.tostring(root, encoding="unicode") + "\n")


def render_lifecycle(outdir, cases_path):
    cases = json.loads(Path(cases_path).read_text()) if Path(cases_path).exists() else {"cases": []}
    root = svg_start("SSH bootstrap and direct data lifetime",
                     "Normal handoff vs deliberate SSH SIGKILL after handoff; bars show observed process/session intervals")
    plot_w = W - PAD_L - PAD_R
    plot_h = H - PAD_T - PAD_B
    rows = cases.get("cases", [])
    if not rows:
        add_text(root, W / 2, H / 2, "No lifecycle fault-injection data available", 16, "middle")
        (outdir / "ssh-lifecycle.svg").write_text(ET.tostring(root, encoding="unicode") + "\n")
        return
    max_ms = max(c.get("transfer_end_ms", c.get("data_end_ms", 1)) for c in rows)
    max_ms = max(max_ms, 1)
    ymax = max(1000, math.ceil(max_ms / 10000) * 10000)
    for i in range(6):
        x = PAD_L + plot_w * i / 5
        add_line(root, x, PAD_T, x, PAD_T + plot_h)
        add_text(root, x, PAD_T + plot_h + 22, f"{ymax * i / 5 / 1000:.1f}s", 10, "middle")
    add_line(root, PAD_L, PAD_T, PAD_L, PAD_T + plot_h, "axis")
    add_line(root, PAD_L, PAD_T + plot_h, PAD_L + plot_w, PAD_T + plot_h, "axis")
    add_text(root, PAD_L + plot_w / 2, PAD_T + plot_h + 42, "Elapsed since bootstrap start", 11, "middle")
    lane_h = min(34, plot_h / (len(rows) + 1))
    for i, c in enumerate(rows):
        y_ssh = PAD_T + 18 + i * lane_h * 2
        y_data = y_ssh + lane_h * 0.62
        def x_of(ms): return PAD_L + plot_w * min(ms, ymax) / ymax
        ssh_start = c.get("ssh_start_ms", 0)
        ssh_end = c.get("ssh_end_ms", c.get("kill_ms", 0))
        data_start = c.get("data_start_ms", 0)
        data_end = c.get("data_end_ms", c.get("transfer_end_ms", 0))
        ET.SubElement(root, "rect", x=f"{x_of(ssh_start):.1f}", y=f"{y_ssh:.1f}", width=f"{max(1,x_of(ssh_end)-x_of(ssh_start)):.1f}", height=f"{lane_h*0.45:.1f}",
                      fill="#4c78a8", stroke="#30363d")
        ET.SubElement(root, "rect", x=f"{x_of(data_start):.1f}", y=f"{y_data:.1f}", width=f"{max(1,x_of(data_end)-x_of(data_start)):.1f}", height=f"{lane_h*0.45:.1f}",
                      fill="#54a24b", stroke="#30363d")
        label = c.get("label", f"case {i+1}")
        add_text(root, PAD_L, y_ssh - 4, label, 11, "start", "600")
        if c.get("ssh_killed"):
            kx = x_of(ssh_end)
            ET.SubElement(root, "path", d=f"M {kx:.1f} {y_ssh-6:.1f} L {kx+8:.1f} {y_ssh+2:.1f} L {kx:.1f} {y_ssh+10:.1f} L {kx-8:.1f} {y_ssh+2:.1f} Z",
                          fill="#e45756", stroke="#30363d")
            add_text(root, kx + 10, y_ssh - 8, "SSH SIGKILL", 10, "start", "600", "#e45756")
        add_text(root, x_of(data_end) + 4, y_data + lane_h * 0.4, f"data ends {data_end/1000:.1f}s", 9)
    # Legend
    ET.SubElement(root, "rect", x=str(PAD_L), y=str(H - 40), width="14", height="10", fill="#4c78a8")
    add_text(root, PAD_L + 20, H - 31, "SSH bootstrap process", 11)
    ET.SubElement(root, "rect", x=str(PAD_L + 190), y=str(H - 40), width="14", height="10", fill="#54a24b")
    add_text(root, PAD_L + 210, H - 31, "authenticated direct data session", 11)
    add_text(root, W - PAD_R, H - 18, "From lifecycle.json; times relative to process start", 10, "end")
    ET.indent(root, space="  ")
    (outdir / "ssh-lifecycle.svg").write_text(ET.tostring(root, encoding="unicode") + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="docs/assets/benchmarks/results.json")
    ap.add_argument("--outdir", default="docs/assets/benchmarks")
    ap.add_argument("--lifecycle", default="docs/assets/benchmarks/lifecycle.json")
    args = ap.parse_args()
    doc = load_results(args.results)
    outdir = Path(args.outdir); outdir.mkdir(parents=True, exist_ok=True)
    render_throughput(doc, outdir, "upload", "large-128MiB",
                      "Upload throughput by transport (128 MiB)",
                      "upload-throughput.svg")
    render_throughput(doc, outdir, "download", "small-16MiB",
                      "Download throughput by transport (16 MiB)",
                      "download-throughput.svg")
    render_handoff(doc, outdir)
    render_lifecycle(outdir, args.lifecycle)
    for name in ("upload-throughput.svg", "download-throughput.svg", "handoff-latency.svg", "ssh-lifecycle.svg"):
        p = outdir / name
        ET.parse(p)
        print(f"{p} ({p.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
